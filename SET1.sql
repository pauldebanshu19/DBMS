CREATE SEQUENCE EMP_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE EMPLOYEE (
     EID VARCHAR2(5) PRIMARY KEY,
     ENAME VARCHAR2(20) NOT NULL,
     SALARY NUMBER CHECK (SALARY BETWEEN 10000 AND 30000),
     CITY VARCHAR2(20) NOT NULL,
     DOB DATE,
     EXP NUMBER(3)
);

