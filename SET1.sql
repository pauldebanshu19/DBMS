SELECT ENAME,FLOOR (MONTHS_BETWEEN(SYSDATE,DOB)/12) AS AGE FROM EMPLOYEE;

-- 2
SELECT MAX(SALARY) AS MAX_SALARY FROM EMPLOYEE;

-- 3
SELECT D.DNAME,MAX(E.SALARY) AS MAX_SALARY
FROM EMPLOYEE E
JOIN WORK W ON E.EID=W.EID
JOIN DEPARTMENT D ON W.DID=D.DID
GROUP BY D.DNAME;
